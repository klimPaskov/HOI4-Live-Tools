#!/usr/bin/env python3
"""Generate docs/TOOLS_MACOS.md from the tool descriptors in native/src/launch/macos*.rs (static, no game needed).
Usage: python3 scripts/gen_tool_index.py > docs/TOOLS_MACOS.md"""
import re, sys, pathlib, json
root = pathlib.Path(__file__).resolve().parent.parent / "native/src/launch"
files = [root / "macos.rs"] + sorted((root / "macos").rglob("*.rs"))
tools = {}
pat = re.compile(r'"name"\s*:\s*"(hoi4_[a-z0-9_]+)"\s*,\s*"description"\s*:\s*"((?:[^"\\]|\\.)*)"', re.S)
for f in files:
    text = f.read_text(errors="replace")
    for m in pat.finditer(text):
        name, desc = m.group(1), m.group(2)
        tail = text[m.end(): m.end() + 1500]
        needs_lease = "lease_token" in re.split(r'"name"\s*:\s*"hoi4_', tail)[0]
        try:
            desc = json.loads('"' + desc + '"')
        except Exception:
            pass
        tools.setdefault(name, (desc, needs_lease, f.name))
# Tools built offline from GUI definitions (fleetops/invasion/faction modules) assemble their text with
# format!("{}...", kit::UNVALIDATED) or schema("name", &format!("...")); the prefix is added here.
UNVALIDATED = "UNVALIDATED (no live test yet) - "
constants = {"TOOL": "hoi4_naval_invasion", "INCOMING": "hoi4_diplomacy_incoming"}
pat_schema = re.compile(r'schema\(\s*"(hoi4_[a-z0-9_]+)"\s*,\s*&format!\(\s*"((?:[^"\\]|\\.)*)"', re.S)
pat_format = re.compile(r'"name"\s*:\s*(?:"(hoi4_[a-z0-9_]+)"|(TOOL|INCOMING))\s*,\s*"description"\s*:\s*format!\(\s*"\{\}((?:[^"\\]|\\.)*)"', re.S)
for f in files:
    text = f.read_text(errors="replace")
    for m in pat_schema.finditer(text):
        tools.setdefault(m.group(1), (UNVALIDATED + m.group(2), True, f.name))
    for m in pat_format.finditer(text):
        name = m.group(1) or constants[m.group(2)]
        # The read form of hoi4_diplomacy_incoming needs no lease; every other one is an action.
        needs_lease = name != "hoi4_diplomacy_incoming"
        tools.setdefault(name, (UNVALIDATED + m.group(3), needs_lease, f.name))
domains = [
    ("Time, plans and events", r"^hoi4_(time|plan|plan_run|wait_for|events|event_choose|capabilities|input_lease|daily_governor|overview)$"),
    ("Economy, construction and production", r"economy|resource|industry|construction|production|state_slots|shortage|trade"),
    ("Research, doctrines, special projects", r"research|technology|doctrine|special_project|mio|intelligence|focus"),
    ("Politics, decisions, diplomacy, wars", r"politic|decision|diplomacy|wars|front_plan|encirclement|war_goal|faction|country_status"),
    ("Army, templates, designs, supply", r"arm(y|ies)|army|template|design|train|deploy|commander|supply|division"),
    ("Navy and air", r"fleet|naval|convoy|air|navy"),
]
# Facts a whole group of tools shares and no single first sentence carries; printed under the group.
notes = {
    "Politics, decisions, diplomacy, wars": (
        "Politics slots (`hoi4_politics_options`, `hoi4_politics_choose`): `slot` is the slot's position in its "
        "category, the order of the slot lines in the game's `common/idea_tags`. Base game: `government` 0 "
        "mobilization law, 1 trade law, 2 economy law, 3-5 political advisors; `research_production` 0 tank, 1 naval, "
        "2 aircraft and 3 materiel designer (Military Industrial Organizations with Arms Against Tyranny: "
        "`hoi4_mio_*`), 4 industrial concern, 5 theorist; `military_staff` 0 chief of army, 1 chief of navy, 2 chief "
        "of air force, 3-5 high command. An advisor is hired from a slot of its own kind. `hoi4_politics_options` "
        "returns `slots`, every slot of the category with its index and holder; offline, "
        "`scripts/hoi4facts/facts.py politics-slots` prints the layout of the installed game and mods."),
}
def domain(n):
    for title, rx in domains:
        if re.search(rx, n):
            return title
    return "Other"
out = ["# macOS tool index (generated)", "",
       "Generated by `scripts/gen_tool_index.py` from the tool descriptors in `native/src/launch/macos*.rs`.",
       "`A` = action (needs `lease_token` and `request_id`), `R` = read (no lease, never moves the cursor or pauses).",
       "Descriptions are the tools' own text; see `PLAYBOOK_TOOL_GAPS.md` for validation status and limits.", ""]
groups = {}
for n, (d, a, f) in sorted(tools.items()):
    groups.setdefault(domain(n), []).append((n, d, a))
for title, _ in domains + [("Other", "")]:
    rows = groups.get(title)
    if not rows:
        continue
    out += [f"## {title}", ""]
    for n, d, a in rows:
        tag = "UNVALIDATED (no live test yet):"
        body = d.strip()
        prefix = ""
        if body.startswith(tag):
            prefix, body = tag + " ", body[len(tag):].strip()
        first = prefix + re.split(r'(?<=[.;:])\s', body, maxsplit=1)[0]
        first = first[:260]
        out.append(f"- `{n}` ({'A' if a else 'R'}): {first}")
    out.append("")
    if title in notes:
        out += [notes[title], ""]
print("\n".join(out))
